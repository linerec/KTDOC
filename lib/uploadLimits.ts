/**
 * 업로드 용량 한도 — 클라이언트(고르는 순간)와 서버 라우트(최종 방어)가 공유한다.
 *
 * ## 왜 이 숫자인가
 *
 * 파일은 이제 **Vercel 함수를 지나가지 않는다.** 브라우저가 서명받은 주소로 R2에
 * 곧장 올린다(lib/r2/directUpload.ts). 그래서 예전의 진짜 벽이었던
 * **Vercel 요청 본문 4.5MB**가 경로에서 사라졌다.
 *
 * 그 4.5MB는 플랜을 올려도 그대로다(Pro도 동일). 2026-08까지 이 파일은 "바디
 * 한도가 100MB로 올랐다"는 잘못된 전제로 15MB를 허용하고 있었고, 그 결과
 * 4.5~15MB 사진은 **화면이 받아준 뒤 서버가 413으로 거절**했다 — 올리는 분에게는
 * "왜 안 되는지 알 수 없는 실패"였다. 근거: 프로덕션 실측(6MB→413, 3MB→통과),
 * https://vercel.com/docs/functions/limitations
 *
 * 지금 상한을 정하는 것은 플랫폼이 아니라 **상식**이다. 폰 원본 사진은 2~10MB,
 * 큰 카메라 사진도 50MB를 넘지 않는다. 그보다 큰 파일은 사진이 아니라 잘못 고른
 * 파일(영상 등)일 가능성이 높다. R2 자체는 단일 PUT 5GB까지 받는다.
 */

/** 사진 한 장의 상한. 브라우저 → R2 직행이라 이제 넉넉하게 잡을 수 있다. */
export const MAX_UPLOAD_FILE_BYTES = 50 * 1024 * 1024;

/** UI 안내 문구·에러 메시지용 한도 표기 */
export const MAX_UPLOAD_FILE_MB = 50;

